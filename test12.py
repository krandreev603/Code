# изчисляване на количеството гориво: Напишете програма, която по въведени разстояние в километри и разход на гориво в литри на 100 километра изчислява количеството гориво, необходимо за пътуването.

distance_km = float(input("Въведете разстояние в километри: "))
fuel_consumption = float(input("Въведете разход на гориво (л/100 км): "))

fuel_needed = (distance_km * fuel_consumption) / 100

print(f"Необходимо количество гориво: {fuel_needed:.2f} литра")
